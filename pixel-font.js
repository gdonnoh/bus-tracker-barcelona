/**
 * Disegna un carattere pixel per pixel sul canvas
 * @param {CanvasRenderingContext2D} ctx - Contesto canvas
 * @param {string} char - Carattere da disegnare
 * @param {number} x - Posizione X (in pixel)
 * @param {number} y - Posizione Y (in pixel)
 * @param {string} color - Colore RGB esadecimale
 * @param {boolean} small - Usa font piccolo (3x5) invece di grande (5x7)
 */
function drawChar(ctx, char, x, y, color, small = false) {
    const font = small ? PIXEL_FONT_SMALL : PIXEL_FONT;
    const charUpper = char.toUpperCase();
    const charData = font[charUpper] || font['?'] || font[' '];
    const width = small ? 3 : 5;
    const height = small ? 5 : 7;
    
    ctx.fillStyle = color;
    
    for (let row = 0; row < height; row++) {
        const rowData = charData[row] || 0;
        for (let col = 0; col < width; col++) {
            if (rowData & (1 << (width - 1 - col))) {
                ctx.fillRect(x + col, y + row, 1, 1);
            }
        }
    }
}

/**
 * Disegna una stringa pixel per pixel
 * @param {CanvasRenderingContext2D} ctx - Contesto canvas
 * @param {string} text - Testo da disegnare
 * @param {number} x - Posizione X iniziale
 * @param {number} y - Posizione Y iniziale
 * @param {string} color - Colore RGB
 * @param {boolean} small - Usa font piccolo
 * @param {number} spacing - Spaziatura tra caratteri (default: 1 pixel)
 */
function drawText(ctx, text, x, y, color, small = false, spacing = 1) {
    const charWidth = small ? 4 : 6; // 3px + 1px spacing o 5px + 1px spacing
    let currentX = x;
    
    for (let i = 0; i < text.length; i++) {
        drawChar(ctx, text[i], currentX, y, color, small);
        currentX += charWidth;
    }
    
    return currentX;
}

